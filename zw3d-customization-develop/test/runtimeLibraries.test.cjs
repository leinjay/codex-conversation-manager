const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { runProcess } = require('../dist/process');
const { findExecutable, runtime, debugConfiguration } = require('../dist/core');
const { inspectElfLibraries, inspectRuntimeLibraries, requireRuntimeLibraries } = require('../dist/runtimeLibraries');

test('actual runtime resolves transitive plugin libraries, honors overrides/RPATH and stops launch for missing dependencies', async t => {
  const cc = await findExecutable('gcc');
  assert.ok(cc, 'Tests require an existing gcc; no tool is installed');
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'zw3d runtime '));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const files = path.join(root, 'SDK/files');
  const mold = path.join(files, 'ZWMold/Bin');
  const apilibs = path.join(files, 'apilibs');
  const build = path.join(root, 'build_debug/plugin');
  for (const dir of [mold, apilibs, build, path.join(files, 'api/inc')]) await fs.mkdir(dir, { recursive: true });
  await fs.writeFile(path.join(files, 'api/inc/zwapi_command.h'), '');
  await fs.writeFile(path.join(files, 'libZW3D.so'), '');
  const marker = path.join(root, 'constructor-must-not-run');
  const leafName = 'libzwprobe_leaf.so';
  const midName = 'libzwprobe_middle.so';
  const leaf = path.join(mold, leafName);
  const middle = path.join(apilibs, midName);
  const built = path.join(build, 'Probe.so');
  const deployed = path.join(apilibs, 'Probe.so');
  await fs.writeFile(path.join(root, 'leaf.c'), `#include <stdio.h>\n__attribute__((constructor)) static void init(){FILE *f=fopen(${JSON.stringify(marker)},"w");if(f)fclose(f);}\nint leaf(){return 5;}\n`);
  await fs.writeFile(path.join(root, 'middle.c'), 'extern int leaf(); int middle(){return leaf();}\n');
  await fs.writeFile(path.join(root, 'plugin.c'), 'extern int middle(); int plugin(){return middle();}\n');
  await fs.writeFile(path.join(root, 'host.c'), 'int main(){return 0;}\n');
  await runProcess(cc, ['-shared', '-fPIC', path.join(root, 'leaf.c'), '-Wl,-soname,'+leafName, '-o', leaf]);
  await runProcess(cc, ['-shared', '-fPIC', path.join(root, 'middle.c'), '-L'+mold, '-lzwprobe_leaf', '-Wl,-soname,'+midName, '-o', middle]);
  await runProcess(cc, ['-shared', '-fPIC', path.join(root, 'plugin.c'), '-L'+apilibs, '-lzwprobe_middle', '-o', built]);
  await runProcess(cc, [path.join(root, 'host.c'), '-o', path.join(files, 'zw3d')]);
  await fs.copyFile(built, deployed);
  const project = { root, config: { version:1, projectName:'Probe',libraryName:'Probe',cmakePath:'cmake',cxxPath:cc,gdbPath:await findExecutable('gdb'),zw3dRoot:path.dirname(files),buildDirectory:'build_debug',buildType:'Debug',executable:path.join(files,'zw3d'),apilibs,args:[],environment:{},cmakeArgs:[] } };
  const inherited = process.env.LD_LIBRARY_PATH;
  const launch = await runtime(project);
  assert.ok(launch.env.LD_LIBRARY_PATH.split(':').includes(mold));
  assert.ok(launch.env.LD_LIBRARY_PATH.split(':').includes(apilibs));
  assert.equal(process.env.LD_LIBRARY_PATH, inherited, 'Building launch environment must not change parent environment');
  const debug = await debugConfiguration(project);
  assert.equal(debug.environment.find(item => item.name === 'LD_LIBRARY_PATH').value, launch.env.LD_LIBRARY_PATH);
  const healthy = await inspectRuntimeLibraries(project);
  assert.deepEqual(healthy.issues, []);
  assert.equal(healthy.checks.length, 3);
  await assert.rejects(fs.access(marker), 'Dependency inspection must not run ELF constructors');
  project.config.environment.LD_LIBRARY_PATH = '';
  const overridden = await inspectRuntimeLibraries(project);
  assert.ok(overridden.issues.some(issue => issue.message.includes(midName)), 'Explicit project overrides must be diagnosed, not silently replaced');
  const rpath = path.join(apilibs, 'Rpath.so');
  await runProcess(cc, ['-shared', '-fPIC', path.join(root, 'middle.c'), '-L'+mold, '-lzwprobe_leaf', '-Wl,-rpath,'+mold, '-o', rpath]);
  assert.equal((await inspectElfLibraries(rpath, files, { ...launch.env, LD_LIBRARY_PATH:'' })).status, 'passed', 'Loader RPATH must work without that directory in LD_LIBRARY_PATH');
  delete project.config.environment.LD_LIBRARY_PATH;
  await fs.rename(leaf, leaf+'.removed');
  const broken = await inspectRuntimeLibraries(project);
  assert.ok(broken.issues.some(issue => issue.severity==='error' && issue.message.includes(leafName)));
  await assert.rejects(requireRuntimeLibraries(project, ()=>{}), /已停止启动 ZW3D/);
  await fs.rm(built); await fs.rm(deployed);
  const unbuilt = await inspectRuntimeLibraries(project);
  assert.ok(unbuilt.issues.some(issue => issue.message.includes('插件尚未生成')));
  const script = path.join(root,'not-elf'); await fs.writeFile(script, '#!/bin/sh\ntouch should-not-run\n');
  assert.equal((await inspectElfLibraries(script, root, launch.env)).status, 'unavailable');
});
